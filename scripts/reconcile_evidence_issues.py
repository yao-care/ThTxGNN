#!/usr/bin/env python3
"""
對帳：關閉預測清單更新後已過期的證據監測 issue（2026-11-03）。

check_clinicaltrials.py／check_pubmed.py 依 scripts/drug_list.json（由 extract_drug_list.py 從
docs/_drugs/*.md 的 monitor_inn、predicted_indications 產生）開 issue；預測清單改過之後，
已經開出去的 issue 沒有機制回頭關。本腳本在 extract_drug_list.py 之後、檢查腳本之前執行：

取得全部 open、帶 auto-detected 且帶 clinicaltrials 或 pubmed 標籤的 issue（分頁），符合任一條就
留言並以 not_planned 關閉：
  (a) 標題沒有「→」：2026-10-16 前只按藥名開的舊版 issue
  (b) 藥已不在目前的 drug_list（頁面沒有預測新適應症或 monitor_inn 了）
  (c) issue 內文「### Predicted New Indication(s)」列的預測，一個都不在該藥目前的 predicted_indications
只有部分預測還在的不關、不留言。

跳過：有 assignee、帶 evidence-confirmed／keep*／pinned／security 標籤、有非 bot 的留言、
不是 bot 開的 issue。

每次最多關 RECONCILE_MAX_CLOSE 筆（預設 50），每筆之間 sleep RECONCILE_SLEEP 秒（預設 2，最少 2）。
--dry-run 或沒有 GITHUB_TOKEN 時只讀不寫，列出會關哪些與理由。
"""

import argparse
import json
import os
import re
import sys
import time
from pathlib import Path

import requests

GITHUB_TOKEN = os.environ.get("GITHUB_TOKEN")
GITHUB_REPO = os.environ.get("GITHUB_REPOSITORY", "yao-care/ThTxGNN")
DRUG_LIST_FILE = Path(__file__).parent / "drug_list.json"
API = "https://api.github.com"

MONITOR_LABELS = {"clinicaltrials", "pubmed"}
SKIP_LABELS = {"evidence-confirmed", "pinned", "security", "tfda"}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

REASON_TEXT = {
    "a": "this issue was opened by drug name only, before monitoring was tied to the predicted new indications (2026-10-16).",
    "b": "{drug} is no longer in the monitored drug list (its page no longer lists predicted new indications).",
    "c": "none of the predicted indications listed in this issue are on the drug page any more.",
}
COMMENT = "🤖 Auto-closed: the prediction list has been updated — {reason}" + FOOTER


def headers() -> dict:
    h = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    if GITHUB_TOKEN:
        h["Authorization"] = f"Bearer {GITHUB_TOKEN}"
    return h


def get_all(url: str, params: dict = None) -> list:
    """GET a list endpoint, following Link rel=next pagination."""
    items = []
    params = dict(params or {}, per_page=100)
    while url:
        r = requests.get(url, headers=headers(), params=params, timeout=30)
        r.raise_for_status()
        items.extend(r.json())
        url = r.links.get("next", {}).get("url")
        params = None
    return items


def norm(name: str) -> str:
    name = re.sub(r"\s*\((disease|disorder)\)\s*", " ", name or "", flags=re.I)
    return re.sub(r"\s+", " ", name).strip().lower()


def body_section(body: str, heading: str) -> str:
    m = re.search(r"^### " + re.escape(heading) + r"[ \t]*\r?\n(.*?)(?=^### |\Z)", body or "", re.S | re.M)
    return m.group(1).strip() if m else None


def issue_drug(issue: dict) -> str:
    name = body_section(issue.get("body") or "", "Drug Name")
    if name:
        return name.splitlines()[0].strip()
    m = re.search(r"[:：]\s*(.+?)\s*\(\d+", issue.get("title", ""))
    return m.group(1).strip() if m else ""


def issue_indications(issue: dict) -> list:
    sec = body_section(issue.get("body") or "", "Predicted New Indication(s)")
    if sec is None:
        return None
    return [norm(line[2:]) for line in sec.splitlines() if line.startswith("- ") and line[2:].strip() not in ("", "-")]


def is_bot(user: dict) -> bool:
    return (user or {}).get("type") == "Bot" or (user or {}).get("login", "").endswith("[bot]")


def skip_reason(issue: dict) -> str:
    labels = {l["name"].lower() for l in issue.get("labels", [])}
    if issue.get("assignees"):
        return "assigned"
    hit = labels & SKIP_LABELS or {l for l in labels if l.startswith("keep")}
    if hit:
        return "label " + ",".join(sorted(hit))
    if not is_bot(issue.get("user")):
        return "not opened by bot"
    return ""


def has_human_comment(issue: dict) -> bool:
    if not issue.get("comments"):
        return False
    comments = get_all(issue["comments_url"])
    return any(not is_bot(c.get("user")) for c in comments)


def close_reason(issue: dict, current: dict) -> str:
    if "→" not in issue.get("title", ""):
        return "a"
    drug = issue_drug(issue).lower()
    if drug not in current:
        return "b"
    listed = issue_indications(issue)
    if not listed:
        return ""  # 內文格式看不懂就不動
    if not any(i in current[drug] for i in listed):
        return "c"
    return ""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--dry-run", action="store_true", help="read only; list what would be closed")
    ap.add_argument("--max", type=int, default=int(os.environ.get("RECONCILE_MAX_CLOSE", "50")))
    args = ap.parse_args()
    dry = args.dry_run or not GITHUB_TOKEN
    pause = max(2.0, float(os.environ.get("RECONCILE_SLEEP", "2")))

    data = json.loads(DRUG_LIST_FILE.read_text(encoding="utf-8"))
    current = {d["name"].lower(): {norm(x) for x in d.get("predicted_indications") or []} for d in data["drugs"]}
    print(f"Repo: {GITHUB_REPO}  mode: {'DRY RUN' if dry else 'LIVE'}  max close: {args.max}")
    print(f"Monitored drugs in drug_list: {len(current)}")

    issues = get_all(f"{API}/repos/{GITHUB_REPO}/issues", {"state": "open", "labels": "auto-detected"})
    issues = [i for i in issues if "pull_request" not in i
              and {l["name"] for l in i.get("labels", [])} & MONITOR_LABELS]
    issues.sort(key=lambda i: i["number"])
    print(f"Open auto-detected clinicaltrials/pubmed issues: {len(issues)}")

    counts = {"a": 0, "b": 0, "c": 0, "kept": 0, "skipped": 0}
    closed = 0
    for issue in issues:
        reason = close_reason(issue, current)
        if not reason:
            counts["kept"] += 1
            continue
        skip = skip_reason(issue) or ("human comment" if has_human_comment(issue) else "")
        if skip:
            counts["skipped"] += 1
            print(f"  skip #{issue['number']} ({skip}): {issue['title'][:90]}")
            continue
        if closed >= args.max:
            counts[reason] += 1  # 本次額度用完，下次排程再關
            continue
        counts[reason] += 1
        closed += 1
        drug = issue_drug(issue)
        print(f"  {'would close' if dry else 'close'} #{issue['number']} [{reason}]: {issue['title'][:90]}")
        if dry:
            continue
        body = COMMENT.format(reason=REASON_TEXT[reason].format(drug=drug))
        url = f"{API}/repos/{GITHUB_REPO}/issues/{issue['number']}"
        try:
            requests.post(f"{url}/comments", headers=headers(), json={"body": body}, timeout=30).raise_for_status()
            requests.patch(url, headers=headers(), json={"state": "closed", "state_reason": "not_planned"},
                           timeout=30).raise_for_status()
        except requests.RequestException as e:
            print(f"    Error closing #{issue['number']}: {e}")
        time.sleep(pause)

    total = counts["a"] + counts["b"] + counts["c"]
    print(f"\nStale: {total} (a no-arrow {counts['a']}, b drug gone {counts['b']}, c predictions gone {counts['c']}); "
          f"{'would close' if dry else 'closed'} this run: {closed}; kept: {counts['kept']}; skipped: {counts['skipped']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
